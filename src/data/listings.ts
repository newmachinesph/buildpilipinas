/* -------------------------------------------------------------- helpers --- */
/* ponytail: plain O(n) scans — this is seed data measured in dozens, an index
   would be more code than it saves. */

export const getListing = (id: string): Listing | undefined =>
  LISTINGS.find((l) => l.id === id);

export const getCategory = (slug: string): Category | undefined =>
  CATEGORIES.find((c) => c.slug === slug);

export const getListingsByCategory = (slug: string): Listing[] =>
  LISTINGS.filter((l) => slugify(l.category) === slug);

export const getListingsBySupplier = (slug: string): Listing[] =>
  LISTINGS.filter((l) => l.supplierSlug === slug);
